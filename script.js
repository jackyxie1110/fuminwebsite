const languageButtons = document.querySelectorAll("[data-lang]");
const translatableNodes = document.querySelectorAll("[data-i18n]");
const ariaNodes = document.querySelectorAll("[data-i18n-aria]");
const header = document.querySelector("[data-header]");
const navToggle = document.querySelector("[data-nav-toggle]");
const navPanel = document.querySelector("[data-nav-panel]");

function getAnchorSection() {
  const sections = [...document.querySelectorAll("[data-section]")];
  return sections.reduce((current, section) => {
    const top = section.getBoundingClientRect().top;
    return top <= window.innerHeight * 0.35 ? section : current;
  }, sections[0]);
}

function setLanguage(language) {
  const selected = translations[language] ? language : "zh-Hant-HK";
  const anchor = getAnchorSection();
  const oldTop = anchor.getBoundingClientRect().top;
  const copy = translations[selected];

  translatableNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (copy[key]) node.textContent = copy[key];
  });

  ariaNodes.forEach((node) => {
    const key = node.dataset.i18nAria;
    if (copy[key]) node.setAttribute("aria-label", copy[key]);
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === selected));
  });

  document.documentElement.lang = selected;
  document.title = selected === "en" ? "Fumin Congee | Hong Kong" : "富民粥品｜Fumin Congee";
  document.querySelector('meta[name="description"]').setAttribute("content", copy.metaDescription);

  requestAnimationFrame(() => {
    const newTop = anchor.getBoundingClientRect().top;
    window.scrollBy({ top: newTop - oldTop, behavior: "auto" });
  });

  try { localStorage.setItem("fumin-language", selected); } catch (_) { /* Preferences remain optional. */ }
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

function closeMenu() {
  navToggle.setAttribute("aria-expanded", "false");
  navPanel.classList.remove("open");
  header.classList.remove("menu-open");
  document.body.style.overflow = "";
  const label = translations[document.documentElement.lang]?.menuToggle || translations["zh-Hant-HK"].menuToggle;
  navToggle.querySelector(".sr-only").textContent = label;
}

navToggle.addEventListener("click", () => {
  const willOpen = navToggle.getAttribute("aria-expanded") !== "true";
  navToggle.setAttribute("aria-expanded", String(willOpen));
  navPanel.classList.toggle("open", willOpen);
  header.classList.toggle("menu-open", willOpen);
  document.body.style.overflow = willOpen ? "hidden" : "";
  const currentCopy = translations[document.documentElement.lang] || translations["zh-Hant-HK"];
  navToggle.querySelector(".sr-only").textContent = willOpen ? currentCopy.menuClose : currentCopy.menuToggle;
});

document.querySelectorAll(".site-nav a").forEach((link) => link.addEventListener("click", closeMenu));
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeMenu();
});

window.addEventListener("scroll", () => header.classList.toggle("scrolled", window.scrollY > 28), { passive: true });

const revealObserver = new IntersectionObserver((entries, observer) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.12 });

document.querySelectorAll(".reveal").forEach((element) => revealObserver.observe(element));

const navLinks = [...document.querySelectorAll(".site-nav a")];
const navObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    navLinks.forEach((link) => link.classList.toggle("active", link.hash === `#${entry.target.id}`));
  });
}, { rootMargin: "-35% 0px -60% 0px" });

document.querySelectorAll("#story, #craft, #menu, #visit").forEach((section) => navObserver.observe(section));

